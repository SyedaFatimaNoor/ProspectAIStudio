import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
const lock = JSON.parse(await readFile("package-lock.json", "utf8"));
const result = await build({
  entryPoints: ["supabase/functions/prospectai-worker/index.ts"],
  bundle: true,
  write: false,
  platform: "neutral",
  format: "esm",
  target: "es2022",
  external: ["node:*", "zod", "@supabase/supabase-js"],
});
let code = result.outputFiles[0].text;
for (const name of ["zod", "@supabase/supabase-js"]) {
  const version = lock.packages[`node_modules/${name}`].version;
  code = code.replaceAll(`from "${name}"`, `from "npm:${name}@${version}"`);
}
// The connector deploys one entry file, so this deliberately tracked artifact
// contains our shared provider/validation code. npm imports are version-pinned.
// Deploy a loader importing this exact file at an immutable Git commit, never a branch URL.
await writeFile(
  "supabase/functions/prospectai-worker/bundle.js",
  "// GENERATED by npm run build:worker. No secrets. Do not hand-edit.\n" +
    code,
);
console.log(
  "Built single-file Supabase Edge worker (no credentials embedded).",
);
