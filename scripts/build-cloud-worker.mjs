import { build } from "esbuild";
import { writeFile } from "node:fs/promises";

const result = await build({
  entryPoints: ["supabase/functions/prospectai-worker/index.ts"],
  bundle: true,
  write: false,
  platform: "neutral",
  format: "esm",
  target: "es2022",
  metafile: true,
});
let code = result.outputFiles[0].text;
if (
  Object.values(result.metafile.outputs).some((output) => output.imports.length)
) {
  throw new Error(
    "Edge deployment must be a single self-contained file without runtime imports.",
  );
}
// The connector deploys one entry file, so this deliberately tracked artifact
// contains our shared portable source adapter. Deploy its CONTENT directly;
// the connector does not bundle remote/npm imports.
await writeFile(
  "supabase/functions/prospectai-worker/bundle.js",
  "// GENERATED by npm run build:worker. No secrets. Do not hand-edit.\n" +
    code,
);
console.log(
  "Built single-file Supabase Edge worker (no credentials embedded).",
);
